export function ScamIndicatorCard({ signal }: { signal: DetectedSignal }) {
  return (
    <details className="indicator">
      <summary>
        <span className={`indicator-mark risk-${signal.severity}`}>
          <ShieldAlert size={16} aria-hidden="true" />
        </span>
        <span className="flex-1">{signal.title}</span>
        <ChevronDown
          size={16}
          className="disclosure-arrow"
          aria-hidden="true"
        />
      </summary>
      <div className="indicator-content">
        <p>{signal.explanation}</p>
        {signal.matchedText && (
          <p className="matched-text">
            Matched wording: <q>{signal.matchedText}</q>
          </p>
        )}
      </div>
    </details>
  );
}

export const agentIcons: Record<AgentFinding["role"], LucideIcon> = {
  investigator: Search,
  prosecutor: Scale,
  defender: ShieldCheck,
  judge: Gavel,
};
export const agentSubtitles: Record<AgentFinding["role"], string> = {
  investigator: "Follow the evidence",
  prosecutor: "Examine the warning signs",
  defender: "Consider the other side",
  judge: "Weigh the full picture",
};

export function AgentCard({ agent }: { agent: AgentFinding }) {
  const Icon = agentIcons[agent.role];
  return (
    <article className="card agent-card">
      <span className="icon-tile">
        <Icon size={22} strokeWidth={1.6} aria-hidden="true" />
      </span>
      <h3 className="capitalize">{agent.role}</h3>
      <p className="agent-subtitle">{agentSubtitles[agent.role]}</p>
      <span className="phase-label">Coming in Phase 2</span>
      <details className="agent-details">
        <summary>
          About this role
          <ChevronDown
            size={14}
            className="disclosure-arrow"
            aria-hidden="true"
          />
        </summary>
        <p>{agent.description}</p>
      </details>
    </article>
  );
}

