export function RiskBadge({ level }: { level: RiskLevel }) {
  const label = {
    high: "High risk",
    medium: "Medium risk",
    low: "Low indicators",
  }[level];
  return (
    <span className={`risk-badge risk-${level}`}>
      <span className="risk-dot" aria-hidden="true" />
      {label}
    </span>
  );
}

